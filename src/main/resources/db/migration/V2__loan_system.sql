CREATE SEQUENCE member_seq INCREMENT BY 50;
CREATE SEQUENCE loan_seq INCREMENT BY 50;
CREATE SEQUENCE book_copy_seq INCREMENT BY 50;

CREATE SEQUENCE inventory_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE BOOK_COPY (
    ID BIGINT PRIMARY KEY,
    BOOK_ID BIGINT NOT NULL REFERENCES BOOKS(ID) ON DELETE CASCADE,
    INVENTORY_NUMBER VARCHAR(30) NOT NULL UNIQUE,
    STATUS VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE','LOANED','DAMAGED', 'WITHDRAWN')),
    VERSION BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE MEMBER (
    ID BIGINT PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    EMAIL VARCHAR(320) NOT NULL UNIQUE
);

CREATE TABLE LOAN(
    ID BIGINT PRIMARY KEY,
    COPY_ID BIGINT NOT NULL REFERENCES BOOK_COPY(ID),
    MEMBER_ID BIGINT NOT NULL REFERENCES MEMBER(ID),
    LOANED_AT DATE NOT NULL,
    DUE_AT DATE NOT NULL,
    RETURNED_AT DATE,
    CHECK ( DUE_AT >= LOANED_AT )
);